use super::catalog::Scenario;
use super::family::{
    Built, COMMAND_LEVEL, Check, ClassSpec, ScenarioDoc, mask_range, random_seeds, seed,
};
use super::layout::Step;
use super::{InputPair, Seed};
use crate::tpm;

pub const STIR_BYTES: usize = 32;

pub fn request_size(byte: u8) -> usize {
    1 + (byte as usize % 64)
}

pub fn input_width(scenario: Scenario) -> usize {
    match scenario {
        Scenario::DrbgGenerate => 1,
        _ => STIR_BYTES,
    }
}

pub fn validate(_scenario: Scenario, _bytes: &[u8]) -> Result<(), String> {
    Ok(())
}

pub fn seeds(scenario: Scenario, campaign_seed: u64, random_pairs: usize) -> Vec<Seed> {
    match scenario {
        Scenario::DrbgGenerate => vec![
            seed("request-32-vs-32", vec![31], vec![31]),
            seed("request-1-vs-64", vec![0], vec![63]),
            seed("request-16-vs-48", vec![15], vec![47]),
        ],
        _ => {
            let mut out = vec![
                seed(
                    "stir-zero-vs-ones",
                    vec![0; STIR_BYTES],
                    vec![0xff; STIR_BYTES],
                ),
                seed(
                    "stir-same-vs-same",
                    vec![0x42; STIR_BYTES],
                    vec![0x42; STIR_BYTES],
                ),
            ];
            out.extend(random_seeds(scenario, campaign_seed, random_pairs, |rng| {
                rng.bytes(STIR_BYTES)
            }));
            out
        }
    }
}

pub fn build(scenario: Scenario, pair: &InputPair) -> Result<Built, String> {
    let class = |input: &[u8]| match scenario {
        Scenario::DrbgGenerate => {
            let n = request_size(input[0]);
            let built =
                tpm::build_command(tpm::TPM_CC_GET_RANDOM, &[], &[], &(n as u16).to_be_bytes());
            let mut params = Vec::new();
            tpm::put_2b(&mut params, &vec![0; n]);
            let expected = tpm::success_response(&[], &params, 0);
            let mask = mask_range(expected.len(), 12, 12 + n);
            let mut spec = ClassSpec::new(Step::new("GetRandom", built.bytes), expected);
            spec.mask = mask;
            spec.check = Some(Check::RandomBytes { len: n });
            spec
        }
        _ => {
            let mut parameters = Vec::new();
            tpm::put_2b(&mut parameters, input);
            let built = tpm::build_command(tpm::TPM_CC_STIR_RANDOM, &[], &[], &parameters);
            ClassSpec::new(
                Step::new("StirRandom", built.bytes),
                tpm::success_response(&[], &[], 0),
            )
        }
    };
    Ok(Built {
        shared: Vec::new(),
        classes: [class(&pair.a), class(&pair.b)],
        model: super::family::PairModel::secret(false).public(
            match scenario {
                Scenario::DrbgGenerate => "requested byte count",
                _ => "additional input",
            },
            pair.a != pair.b,
        ),
        varying_public_values: match scenario {
            Scenario::DrbgGenerate => vec![
                "requested byte count (public)".into(),
                "random output (masked)".into(),
            ],
            _ => vec!["additional input mixed into the DRBG (public)".into()],
        },
    })
}

pub fn doc(scenario: Scenario) -> ScenarioDoc {
    match scenario {
        Scenario::DrbgGenerate => ScenarioDoc {
            harness: COMMAND_LEVEL.into(),
            entry_point: "TPM2_GetRandom (0x17B): restore DRBG state, reseed if due, generate, store state".into(),
            secret: "the DRBG working state (key, V, reseed counter) and the generated bytes".into(),
            attacker_inputs: "the requested byte count (1..64)".into(),
            observable_outputs: "random bytes (masked; checked for length and non-constancy)".into(),
            classes: "two request sizes; equal sizes give identical commands".into(),
            fixed: "everything else".into(),
            timed_region: "one TPMLIB_Process call of GetRandom".into(),
            correctness: "response code and length exact; output non-constant".into(),
            interpretation: "the DRBG state cannot be chosen per class through the ABI: equal-size pairs are an in-library same-operation reference, unequal sizes show the expected output-size dependence; state-dependent timing is not attributable to a class".into(),
            randomized: true,
        },
        _ => ScenarioDoc {
            harness: COMMAND_LEVEL.into(),
            entry_point: "TPM2_StirRandom (0x146): fresh entropy plus the caller's additional input, then reseed".into(),
            secret: "the DRBG state and the fresh entropy".into(),
            attacker_inputs: "32 bytes of additional input".into(),
            observable_outputs: "response code only".into(),
            classes: "two additional inputs".into(),
            fixed: "input length".into(),
            timed_region: "one TPMLIB_Process call of StirRandom (reseed path)".into(),
            correctness: "exact success response".into(),
            interpretation: "exercises the reseed state transition; the input is public, so a signal is a public-input dependence of the reseed path".into(),
            randomized: true,
        },
    }
}
